const express = require("express");

const routeAgent = require("../agents/routeAgent");
const trafficAgent = require("../agents/trafficAgent");
const fuelAgent = require("../agents/fuelAgent");
const carbonAgent = require("../agents/carbonAgent");
const ecoDecisionAgent = require("../agents/ecoDecisionAgent");

const router = express.Router();

router.post("/optimize-route", async (req, res) => {
  try {
    const { origin, destination, vehicle } = req.body;

    if (!origin || !destination) {
      return res.status(400).json({
        success: false,
        message: "Origin and destination are required."
      });
    }

    // 1. Route Optimization Agent
    const routeData = await routeAgent(origin, destination);

    // 2. Traffic Agent
    const trafficData = await trafficAgent(routeData);

    // 3. Fuel Agent
    const fuelData = await fuelAgent(routeData, vehicle);

    // 4. Carbon Agent
    const carbonData = await carbonAgent(fuelData);

    // 5. Eco Decision Agent
    const ecoData = await ecoDecisionAgent(
      routeData,
      trafficData,
      fuelData,
      carbonData
    );

    // --------------------------------------------------
    // Get the real route options generated by Valhalla
    // --------------------------------------------------

    const availableRoutes = routeData.routeOptions || [];
    const routeAnalysis = ecoData.routeAnalysis || [];

    const fastestRoute =
      availableRoutes.find((route) => route.routeType === "fastest") ||
      availableRoutes[0] ||
      null;

    const shortestRoute =
      availableRoutes.find((route) => route.routeType === "shortest") ||
      availableRoutes[1] ||
      null;

    const ecoRoute =
      availableRoutes.find((route) => route.routeType === "eco") ||
      availableRoutes[2] ||
      null;

    const buildRouteSelection = (route) => {
      if (!route) {
        return null;
      }

      const analysis =
        routeAnalysis.find(
          (item) => item.routeType === route.routeType
        ) || {};

            return {
        option: route.option,
        routeType: route.routeType,
        distanceKm: route.distanceKm,
        travelTimeMinutes: route.travelTimeMinutes,
        hasToll: route.hasToll,
        hasHighway: route.hasHighway,
        hasFerry: route.hasFerry,
        geometry: route.geometry,
        fuelOrEnergyUsed: analysis.fuelOrEnergyUsed ?? null,
        co2Emission: analysis.co2Emission ?? null,
        ecoScore: analysis.ecoScore ?? null,
        unit: analysis.unit || fuelData.unit,
        metricsSource: "backend route analysis"
      };
    };

    // --------------------------------------------------
    // Send final response
    // --------------------------------------------------

    res.json({
      success: true,

      message:
        "EcoRoute AI agents completed the request successfully.",

      routeData,

      trafficData,

      fuelData,

      carbonData,

      ecoData,

      routeSelection: {
        availableRouteCount: availableRoutes.length,
        fastest: buildRouteSelection(fastestRoute),
        shortest: buildRouteSelection(shortestRoute),
        eco: buildRouteSelection(ecoRoute)
      }
    });

  } catch (error) {
    console.error(error);

    res.status(500).json({
      success: false,
      message:
        error.message ||
        "Error while processing route optimization."
    });
  }
});

module.exports = router;